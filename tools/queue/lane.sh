#!/usr/bin/env bash
# GPU lane: repeatedly takes the next job from the SHARED job list tools/queue/jobs.txt and runs it on a fixed
# GPU set. Several lanes can share the list; whichever lane gets free GPUs first takes the highest-priority job.
#
#   setsid nohup tools/queue/lane.sh A 0,1,2,3 29610 > logs/queue/lane_A.out 2>&1 < /dev/null &
#   WAIT_PID=<pid> setsid nohup tools/queue/lane.sh B 4,5,6,7 29620 > logs/queue/lane_B.out 2>&1 < /dev/null &
#
# Job list format (re-read whenever a job is picked, so it can be edited/reordered while lanes run):
#   NAME CONFIG SEED [cfg-options ...]        ('#' comments and blank lines are ignored)
# A job is skipped once logs/queue/status.txt has a START, DONE or FAILED line for it. To re-run a job (e.g. its
# lane was killed mid-run; run_job.sh resumes from latest.pth) append "RETRY <name>" to status.txt.
# Before each job the lane waits until WAIT_PID (optional) has exited and every one of its GPUs has had at least
# MIN_FREE_MB free memory (default 100 GB) for FREE_MIN consecutive minutes (default 10), so it never starts on
# top of another big run (small jobs of other users, e.g. 16 GB evals, are tolerated).
# Stop a lane after its current job: touch logs/queue/STOP_<LANE>. Killing the lane pid does not kill the
# running docker job (see tools/gpu_procs.sh).
# NOTE: do not edit this file while lanes are running (bash reads scripts incrementally); edit jobs.txt instead.
set -uo pipefail
LANE=$1; GPUS=$2; PORT=$3
FREE_MIN=${FREE_MIN:-10}
MIN_FREE_MB=${MIN_FREE_MB:-100000}  # SD2 training peaks at ~74 GB/GPU (batch 8)
WAIT_PID=${WAIT_PID:-}
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
JOBS=${JOBS:-tools/queue/jobs.txt}
STATUS=logs/queue/status.txt
LOCK=logs/queue/.queue.lock
mkdir -p logs/queue
touch "$STATUS"

say() { echo "[$(date '+%a %F %T')] lane $LANE: $*" | tee -a "$STATUS"; }

gpus_free() {
    local free
    for g in ${GPUS//,/ }; do
        free=$(nvidia-smi -i "$g" --query-gpu=memory.free --format=csv,noheader,nounits | tr -d ' ')
        (( free >= MIN_FREE_MB )) || return 1
    done
}

wait_for_gpus() {
    if [[ -n $WAIT_PID ]]; then
        while kill -0 "$WAIT_PID" 2>/dev/null; do sleep 60; done
    fi
    local free=0
    while (( free < FREE_MIN )); do
        if gpus_free; then free=$((free + 1)); else free=0; fi
        sleep 60
    done
}

next_job() {
    grep -vE '^\s*(#|$)' "$JOBS" | while read -r name rest; do
        last=$(grep -E "(: (START|DONE|FAILED)|^RETRY) $name( |$)" "$STATUS" | tail -1)
        if [[ -z $last || $last == RETRY* ]]; then echo "$name $rest"; break; fi
    done
}

say "started (gpus $GPUS, port $PORT, wait_pid ${WAIT_PID:-none}, pid $$, jobs $JOBS)"
while true; do
    if [[ -f logs/queue/STOP_$LANE ]]; then say "STOP file found, exiting"; break; fi
    if [[ -z $(next_job) ]]; then say "queue empty, exiting"; break; fi
    say "waiting for free GPUs"
    wait_for_gpus
    WAIT_PID=
    # pick + mark atomically so two lanes never take the same job
    job=$(
        flock 9
        j=$(next_job)
        if [[ -n $j ]]; then
            read -r n c s o <<< "$j"
            say "START $n ($c seed $s ${o:-})" > /dev/null
        fi
        echo "$j"
    ) 9> "$LOCK"
    [[ -z $job ]] && continue
    read -r name config seed opts <<< "$job"
    # shellcheck disable=SC2086
    if tools/queue/run_job.sh "$name" "$config" "$seed" "$GPUS" "$PORT" $opts; then
        say "DONE $name"
    else
        say "FAILED $name (see logs/queue/${name}_job.txt)"
    fi
done
